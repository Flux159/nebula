pub fn random_name() -> String {
    let r = slim_net::rand_id();
    let bytes = r.as_bytes();
    let a = usize::from_str_radix(&r[0..4], 16).unwrap_or(bytes[0] as usize) % ADJECTIVES.len();
    let s = usize::from_str_radix(&r[4..8], 16).unwrap_or(bytes[1] as usize) % SURNAMES.len();
    format!("{}_{}", ADJECTIVES[a], SURNAMES[s])
}
